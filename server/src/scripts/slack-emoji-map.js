/**
 * Convert a Slack emoji name to Unicode.
 * Strips skin-tone suffixes (e.g. "+1::skin-tone-2" → "+1").
 * Returns null for unknown emojis.
 */
export function slackEmojiToUnicode(name) {
  // Strip skin tone variants
  const baseName = name.replace(/::skin-tone-\d+$/, '');
  return SLACK_EMOJI_MAP[baseName] || null;
}

