/**
 * Create a deploy hook URL for the Vercel project (used for auto-rebuilds).
 */
export async function createDeployHook(projectId) {
  const res = await fetch(`https://api.vercel.com/v10/projects/${projectId}/deploy-hooks${vercelTeamParam()}`, {
    method: 'POST',
    headers: vercelHeaders(),
    body: JSON.stringify({
      name: 'bandchat-sync',
      ref: 'main',
    }),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(`Deploy hook creation failed: ${err.error?.message || res.statusText}`);
  }

  const data = await res.json();
  return data.url;
}

/**
 * Trigger a deploy via the deploy hook URL (fire-and-forget POST).
 */
export async function triggerDeploy(deployHookUrl) {
  if (!deployHookUrl) return;
  try {
    await fetch(deployHookUrl, { method: 'POST' });
  } catch {
    // Fire-and-forget — don't throw
    console.error('Website deploy hook trigger failed');
  }
}

/**
 * Create a production deployment directly via Vercel API.
 * Used for initial deploys where the deploy hook may not trigger.
 */
export async function createDeployment(projectId, repoName) {
  const res = await fetch(`https://api.vercel.com/v13/deployments${vercelTeamParam()}`, {
    method: 'POST',
    headers: vercelHeaders(),
    body: JSON.stringify({
      name: projectId,
      project: projectId,
      target: 'production',
      gitSource: {
        type: 'github',
        org: WEBSITE_GITHUB_ORG,
        repo: repoName,
        ref: 'main',
      },
    }),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    console.error('Create deployment failed:', err);
    // Non-fatal — deploy hook or next commit will trigger it
  }
}

