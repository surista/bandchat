/**
 * Website deployment service — manages GitHub + Vercel integration
 * for band websites deployed at bandname.bandchat.app.
 */

import crypto from 'crypto';
import prisma from '../lib/prisma.js';

const GITHUB_TOKEN = process.env.GITHUB_TOKEN;
const VERCEL_TOKEN = process.env.VERCEL_TOKEN;
const VERCEL_TEAM_ID = process.env.VERCEL_TEAM_ID;
const WEBSITE_TEMPLATE_REPO = process.env.WEBSITE_TEMPLATE_REPO || 'bandchat-website-template';
const WEBSITE_GITHUB_ORG = process.env.WEBSITE_GITHUB_ORG || 'bandchat-sites';

function githubHeaders() {
  return {
    Authorization: `Bearer ${GITHUB_TOKEN}`,
    Accept: 'application/vnd.github+json',
    'X-GitHub-Api-Version': '2022-11-28',
    'Content-Type': 'application/json',
  };
}

function vercelHeaders() {
  return {
    Authorization: `Bearer ${VERCEL_TOKEN}`,
    'Content-Type': 'application/json',
  };
}

function vercelTeamParam() {
  return VERCEL_TEAM_ID ? `?teamId=${VERCEL_TEAM_ID}` : '';
}

/**
 * Create a new repo from the template for this band.
 * Uses GitHub's "create repo from template" API (not fork — forks can't target the same org).
 */
export async function forkTemplate(bandSlug) {
  const repoName = `bandchat-${bandSlug}`;
  const res = await fetch(`https://api.github.com/repos/${WEBSITE_GITHUB_ORG}/${WEBSITE_TEMPLATE_REPO}/generate`, {
    method: 'POST',
    headers: {
      ...githubHeaders(),
      Accept: 'application/vnd.github.baptiste-preview+json',
    },
    body: JSON.stringify({
      owner: WEBSITE_GITHUB_ORG,
      name: repoName,
      private: true,
    }),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(`GitHub repo creation failed: ${err.message || res.statusText}`);
  }

  return repoName;
}

/**
 * Write site.config.js to the repo via GitHub Contents API.
 * Retries if the repo isn't ready yet (template API creates repos asynchronously).
 */
export async function writeSiteConfig(repoName, config) {
  const path = 'site.config.js';
  const content = `// Auto-generated by BandChat — do not edit manually\nexport default ${JSON.stringify(config, null, 2)};\n`;
  const encoded = Buffer.from(content).toString('base64');

  // Wait for repo to be ready (template API is async)
  let sha;
  for (let attempt = 0; attempt < 10; attempt++) {
    const getRes = await fetch(`https://api.github.com/repos/${WEBSITE_GITHUB_ORG}/${repoName}/contents/${path}`, {
      headers: githubHeaders(),
    });
    if (getRes.ok) {
      const existing = await getRes.json();
      sha = existing.sha;
      break;
    }
    // Repo not ready yet — wait and retry
    console.log(`Waiting for repo to be ready (attempt ${attempt + 1}/10)...`);
    await new Promise(r => setTimeout(r, 3000));
  }

  if (!sha) {
    throw new Error('GitHub repo not ready after 30s — site.config.js not found');
  }

  const body = {
    message: 'Update site config from BandChat',
    content: encoded,
    sha,
  };

  const res = await fetch(`https://api.github.com/repos/${WEBSITE_GITHUB_ORG}/${repoName}/contents/${path}`, {
    method: 'PUT',
    headers: githubHeaders(),
    body: JSON.stringify(body),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(`GitHub config write failed: ${err.message || res.statusText}`);
  }
}

/**
 * Read the template version (from its package.json) so the UI can show a
 * "Upgrade available: vX.Y.Z" hint when the band's repo is on an older one.
 */
export async function getTemplateVersion() {
  const res = await fetch(
    `https://api.github.com/repos/${WEBSITE_GITHUB_ORG}/${WEBSITE_TEMPLATE_REPO}/contents/package.json`,
    { headers: githubHeaders() }
  );
  if (!res.ok) return null;
  const data = await res.json();
  try {
    const pkg = JSON.parse(Buffer.from(data.content, 'base64').toString('utf-8'));
    return pkg.version || null;
  } catch {
    return null;
  }
}

